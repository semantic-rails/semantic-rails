-- COMPARISON_ORDER_ITEMS: 95368
-- COMPARISON_CUSTOMERS: 939
-- COMPARISON_STORES: 5
-- COMPARISON_CUSTOMER_HISTORY: 7
-- COMPARISON_ORDER_LIFECYCLE: 11
-- COMPARISON_STOREFRONT_SESSIONS: 10

SELECT MIN(ORDERED_AT) AS min_ordered_at, MAX(ORDERED_AT) AS max_ordered_at
FROM COMPARISON_ORDERS;
