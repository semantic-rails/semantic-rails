#!/usr/bin/env python3
"""Write (or with --check, verify) the Architect MCP tool table in docs/ARCHITECT_MCP.md.

The table is generated from the server's own ``tools/list``: each tool's name, title, whether
it writes package files, and the first sentence of its description. ``--check`` exits 1 when the
committed table differs, so the docs cannot list a tool the server lacks or miss one it has.
"""

from __future__ import annotations

import argparse
import asyncio
import re
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from semantic_rails.architect_mcp import create_architect_mcp_server  # noqa: E402

DOC = REPO_ROOT / "docs" / "ARCHITECT_MCP.md"
START = "<!-- architect-tools:start (generated by scripts/architect_tool_table.py) -->"
END = "<!-- architect-tools:end -->"
_SENTENCE = re.compile(r"^(.+?[.!?])(?:\s|$)", re.DOTALL)


def _first_sentence(text: str) -> str:
    flat = " ".join(str(text or "").split())
    match = _SENTENCE.match(flat)
    return (match.group(1) if match else flat).replace("|", "\\|")


def render_table() -> str:
    with tempfile.TemporaryDirectory() as root:
        tools = asyncio.run(create_architect_mcp_server(workspace_root=root).list_tools())
    lines = [
        START,
        f"{len(tools)} tools, in the order the server lists them.",
        "",
        "| Tool | Title | Writes files | What it does |",
        "| --- | --- | --- | --- |",
    ]
    for tool in tools:
        hints = tool.annotations
        title = (hints.title if hints else "") or ""
        writes = "no" if hints is not None and hints.readOnlyHint else "yes"
        lines.append(
            f"| `{tool.name}` | {title} | {writes} | {_first_sentence(tool.description or '')} |"
        )
    lines.append(END)
    return "\n".join(lines)


def updated_doc(text: str) -> str:
    start, end = text.find(START), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{DOC.name}: the generated tool table's markers are missing")
    return text[:start] + render_table() + text[end + len(END) :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the table is stale.")
    args = parser.parse_args(argv)
    current = DOC.read_text(encoding="utf-8")
    wanted = updated_doc(current)
    if current == wanted:
        print("Architect tool table is current.")
        return 0
    if args.check:
        print(
            "docs/ARCHITECT_MCP.md's Architect tool table differs from the server's tool list. "
            "Run: uv run python scripts/architect_tool_table.py",
            file=sys.stderr,
        )
        return 1
    DOC.write_text(wanted, encoding="utf-8")
    print("Wrote the Architect tool table.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
